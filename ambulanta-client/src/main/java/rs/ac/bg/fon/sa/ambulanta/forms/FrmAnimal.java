    private void populateComboBox() {
        
        try {
            cbSpecies.setModel(new DefaultComboBoxModel(Species.values()));
            cbSpecies.setSelectedIndex(-1);
            
            cbGender.setModel(new DefaultComboBoxModel(Gender.values()));
            cbGender.setSelectedIndex(-1);
            
            List<Owner> owners = new ArrayList<>();
            owners = Controller.getInstance().getAllOwners();
            cbOwners.setModel(new DefaultComboBoxModel(owners.toArray()));
            cbOwners.setSelectedIndex(-1);
            
        } catch (Exception ex) {
            System.out.println("Nisu ucitani vlasnici. Doslo je do greske.");
        }
        
    }
    
    private void setSpinner() {
        SpinnerNumberModel spinerModel = new SpinnerNumberModel(LocalDate.now().getYear(), 0,LocalDate.now().getYear() , 1);
        spYearOfBirth.setModel(spinerModel);
        NumberEditor editor = new NumberEditor(spYearOfBirth, "0");
        spYearOfBirth.setEditor(editor);
    }

    private void prepareView() {
        
        txtIDAnimal.setEditable(false);
        
        if(mode==FormMode.FORM_ADD_MODE){

            txtFirstnameOwner.setEditable(false);
            txtLastnameOwner.setEditable(false);
            chkLoyaltyCard.setEnabled(false);
            txtPhone.setEditable(false);
            txtEmail.setEditable(false);
            txtAddress.setEditable(false);
        }
        
        if (mode == FormMode.FORM_VIEW_MODE) {

            txtIDAnimal.setText(animal.getId().toString());
            txtNameAnimal.setText(animal.getName());

            for (int i = 0; i < cbSpecies.getItemCount(); i++) {
                Species s = (Species) cbSpecies.getItemAt(i);
                if (s.equals(animal.getSpecies())) {
                    cbSpecies.setSelectedIndex(i);
                    break;
                }
            }

            for (int i = 0; i < cbGender.getItemCount(); i++) {
                Gender g = (Gender) cbGender.getItemAt(i);
                if (g.equals(animal.getGender())) {
                    cbGender.setSelectedIndex(i);
                    break;
                }
            }

            spYearOfBirth.setValue(animal.getYearOfBirth());

            txtJMBGOwner.setText(animal.getOwner().getJmbg().toString());
            txtFirstnameOwner.setText(animal.getOwner().getFirstname());
            txtLastnameOwner.setText(animal.getOwner().getLastname());
            chkLoyaltyCard.setSelected(animal.getOwner().getLoyaltyCard());
            txtPhone.setText(animal.getOwner().getPhone());
            txtEmail.setText(animal.getOwner().getEmail());
            txtAddress.setText(animal.getOwner().getAddress());

                cbOwners.setVisible(false);
                btnFindOwner.setVisible(false);
                btnAddAnimal.setVisible(false);
                btnSaveAnimal.setVisible(false);

                txtNameAnimal.setEditable(false);
                spYearOfBirth.setEnabled(false);
                cbSpecies.setEnabled(false);
                cbGender.setEnabled(false);
                
                

                txtJMBGOwner.setEditable(false);
                txtFirstnameOwner.setEditable(false);
                txtLastnameOwner.setEditable(false);
                chkLoyaltyCard.setEnabled(false);
                txtPhone.setEditable(false);
                txtEmail.setEditable(false);
                txtAddress.setEditable(false);

                setSize(460, 680);
        }
    }

    public void populateOwnerFields() {
        
          Owner owner = (Owner) cbOwners.getSelectedItem();
          if(owner!=null){
          txtFirstnameOwner.setText(owner.getFirstname());
          txtLastnameOwner.setText(owner.getLastname());
          if(owner.getLoyaltyCard()==true){
              chkLoyaltyCard.setSelected(true);
          } else chkLoyaltyCard.setSelected(false);
          txtPhone.setText(owner.getPhone());
          txtEmail.setText(owner.getEmail());
          txtAddress.setText(owner.getAddress());
          }
    }

