    private void btnSaveAnimalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveAnimalActionPerformed
         try {
             
            if(animal.getId()==null) throw new Exception("Prvo morate kreirati životinju!");
            if(cbSpecies.getSelectedItem()==null) throw new Exception("Morate uneti vrstu!");
            if(cbGender.getSelectedItem()==null) throw new Exception("Morate uneti pol!");
                
//            validateForm();
            
            animal.setSpecies((Species) cbSpecies.getSelectedItem());
            animal.setGender((Gender) cbGender.getSelectedItem());
            animal.setId(Long.valueOf(txtIDAnimal.getText()));
            animal.setYearOfBirth((int) spYearOfBirth.getValue());
            if(!txtNameAnimal.getText().isEmpty()) {
                animal.setName(txtNameAnimal.getText());
            } else animal.setName("nema");
            Owner owner = (Owner) cbOwners.getSelectedItem();
            animal.setOwner(owner);
            
            animal = Controller.getInstance().editAnimal(animal);
        
            JOptionPane.showMessageDialog(this, "Sistem je zapamtio životniju ["+animal.getId()+"]", "Informacija", JOptionPane.INFORMATION_MESSAGE);
            this.setVisible(false);

            FrmAnimal form = new FrmAnimal( (Frame)this.getParent(),true,FormMode.FORM_VIEW_MODE, animal);
            form.setVisible(true);
            
            
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Sistem ne može da zapamti životinju.", "Greška", JOptionPane.ERROR_MESSAGE);
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greška", JOptionPane.ERROR_MESSAGE);

        }

    }//GEN-LAST:event_btnSaveAnimalActionPerformed

