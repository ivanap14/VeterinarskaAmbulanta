    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed
           
        try {
            validateForm();
            
            chkAll.setSelected(false);
            chkSort.setSelected(false);
            
            List<Intervention> interventions = new ArrayList<>();
            
            if(chkIDIntervention.isSelected()){
                List<Intervention> interventions1 = new ArrayList<>();
                String criteria = txtIDIntervention.getText();
                interventions1 = Controller.getInstance().getInterventionsByInterventionCriteria(criteria);
                interventions.addAll(interventions1);
            }
            if(chkIDVeterinarian.isSelected()){
                List<Intervention> interventions1 = new ArrayList<>();
                String criteria = txtIDVeterinarian.getText();
                interventions1 = Controller.getInstance().getInterventionsByVeterinarianCriteria(criteria);
                if(interventions.isEmpty()){
                   interventions.addAll(interventions1); 
                } else interventions.retainAll(interventions1); //DODAJE U LISTU samo zajednicke elemente (AND-presek logika)
                                                                    //U klasi Intervention mora da se uradi override equals() i hashCode() metoda po id-ju
                                                                    //kako bi se elementi poredili po id-u a ne referenci 
            }
            
            if(chkIDAnimal.isSelected()){
                List<Intervention> interventions1 = new ArrayList<>();
                String criteria = txtIDAnimal.getText();
                interventions1 = Controller.getInstance().getInterventionsByAnimalCriteria(criteria);
                if(interventions.isEmpty()){
                   interventions.addAll(interventions1); 
                } else interventions.retainAll(interventions1);
            }
            
            
            if(chkNameService.isSelected()){ 
                List<Intervention> interventions1 = new ArrayList<>();
                String criteria = txtNameService.getText();
                interventions1 = Controller.getInstance().getInterventionsByServiceCriteria(criteria);
                if(interventions.isEmpty()){
                   interventions.addAll(interventions1); 
                } else interventions.retainAll(interventions1);
            }
            
            if(chkDateIntervention.isSelected()){
                List<Intervention> interventions1 = new ArrayList<>();
                String criteria = txtDateIntervention.getText();
                DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd.MM.yyyy");
                LocalDate localDate = LocalDate.parse(criteria, formatter);
                String criteriaDate = localDate.toString();
                criteriaDate=criteriaDate+"Date";//!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
                interventions1 = Controller.getInstance().getInterventionsByInterventionCriteria(criteriaDate);
                if(interventions.isEmpty()){
                   interventions.addAll(interventions1); 
                } else interventions.retainAll(interventions1);
            }
            
            if(chkAmountGreaterThan .isSelected()){
                List<Intervention> interventions1 = new ArrayList<>();
                String criteria = txtAmountGreaterThan.getText();
                criteria=criteria+">";//!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
                interventions1 = Controller.getInstance().getInterventionsByInterventionCriteria(criteria);
                if(interventions.isEmpty()){
                   interventions.addAll(interventions1); 
                } else interventions.retainAll(interventions1);
            }
            
            if(chkAmountLessThan .isSelected()){
                List<Intervention> interventions1 = new ArrayList<>();
                String criteria = txtAmountLessThan.getText();
                criteria=criteria+"<";//!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
                interventions1 = Controller.getInstance().getInterventionsByInterventionCriteria(criteria);
                if(interventions.isEmpty()){
                   interventions.addAll(interventions1); 
                } else interventions.retainAll(interventions1);
            }
            
            if(chkLastnameVeterinarian.isSelected()){
                List<Intervention> interventions1 = new ArrayList<>();
                String criteria = txtLastnameVeterinarian.getText();
                criteria=criteria+"Lastname";//!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
                interventions1 = Controller.getInstance().getInterventionsByVeterinarianCriteria(criteria);
                if(interventions.isEmpty()){
                   interventions.addAll(interventions1); 
                } else interventions.retainAll(interventions1);
            }
            
            
            if(chkSpeciesAnimal.isSelected()){
                List<Intervention> interventions1 = new ArrayList<>();
                String criteria = txtSpeciesAnimal.getText();
                criteria=criteria+"Species";//!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
                interventions1 = Controller.getInstance().getInterventionsByAnimalCriteria(criteria);
                if(interventions.isEmpty()){
                   interventions.addAll(interventions1); 
                } else interventions.retainAll(interventions1);
            }

            
            interventions = interventions.stream().distinct().collect(Collectors.toList());
            tblIntervention.setModel(new TableModelIntervention(interventions));

            
            if(!interventions.isEmpty()){
                JOptionPane.showMessageDialog(this, "Sistem je našao interevncije po zadatim kriterijumima", "Poruka", JOptionPane.INFORMATION_MESSAGE);
            } else{
                JOptionPane.showMessageDialog(this, "Sistem ne može da nađe intervencije po zadatim kriterijumima!", "Greska", JOptionPane.ERROR_MESSAGE);
            }
            } catch (Exception ex) {
//                JOptionPane.showMessageDialog(this, "Sistem ne može da nađe intervencije po zadatim kriterijumima!\n"+ex.getMessage(), "Greska", JOptionPane.ERROR_MESSAGE);
                JOptionPane.showMessageDialog(this, "Sistem ne može da nađe intervencije po zadatim kriterijumima.", "Greska", JOptionPane.ERROR_MESSAGE);
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Greška", JOptionPane.ERROR_MESSAGE);
            }
            
    }//GEN-LAST:event_btnFindActionPerformed

