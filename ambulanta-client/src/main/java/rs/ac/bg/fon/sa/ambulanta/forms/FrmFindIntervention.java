    private void validateForm() throws Exception {
        Boolean error=false;
        lblAmountGraterThan.setText("");
        lblAmountLessThan.setText("");
        lblIDAnimal.setText("");
        lblIDIntervention.setText("");
        lblNameService.setText("");
        lblIDVeterinarian.setText("");
        lblDateIntervention.setText("");
        lblDateIntervention1.setVisible(true);
        lblLastanameVeterinarian.setText("");
        lblSpecies.setText("");
        
        if (!txtAmountGreaterThan.getText().matches("\\d+") && chkAmountGreaterThan.isSelected()) {
            lblAmountGraterThan.setText("Polje sme da sadrži samo brojeve");
            error=true;
            
        }
        if (!txtAmountLessThan.getText().matches("\\d+") && chkAmountLessThan.isSelected()) {
            lblAmountLessThan.setText("Polje sme da sadrži samo brojeve");
            error=true;
        }
        if (!txtIDAnimal.getText().matches("\\d+") && chkIDAnimal.isSelected()) {
            lblIDAnimal.setText("Polje sme da sadrži samo brojeve");
            error=true;
        }
        if (!txtIDIntervention.getText().matches("\\d+") && chkIDIntervention.isSelected()) {
            lblIDIntervention.setText("Polje sme da sadrži samo brojeve");
            error=true;
        }
        if (!txtIDVeterinarian.getText().matches("\\d+") && chkIDVeterinarian.isSelected()) {
            lblIDVeterinarian.setText("Polje sme da sadrži samo brojeve");
            error=true;
        }
        if (!txtLastnameVeterinarian.getText().matches("[\\p{L} ]+") && chkLastnameVeterinarian.isSelected()) {
            lblLastanameVeterinarian.setText("Polje sme da sadrži samo slova");
            error=true;
        }
        if (!txtNameService.getText().matches("[\\p{L} ]+") && chkNameService.isSelected()) {
            lblNameService.setText("Polje sme da sadrži samo slova");
            error=true;
        }
        if (!txtSpeciesAnimal.getText().matches("[\\p{L} ]+") && chkSpeciesAnimal.isSelected()) {
            lblSpecies.setText("Polje sme da sadrži samo slova");
            error=true;
        }
        
        if (!txtDateIntervention.getText().matches("\\d{2}\\.\\d{2}\\.\\d{4}") && chkDateIntervention.isSelected()) {
            lblDateIntervention1.setVisible(false);
            lblDateIntervention.setText("Datum mora biti u formatu dd.mm.gggg");
            error=true;
  
        }
        
        if(error){
            throw new Exception("Niste ispravno popunili polje/a!");
        }
    }
