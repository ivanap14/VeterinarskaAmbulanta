    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        try {
            
            specialization.setName(txtName.getText());
            specialization.setCategory((Category) cbCategory.getSelectedItem());
            specialization.setDescription(txtDescription.getText());
            
            specialization = Controller.getInstance().addNewSpecialization(specialization);
            
            JOptionPane.showMessageDialog(this, "Sistem je zapamtio specijalizaciju", "Greška", JOptionPane.INFORMATION_MESSAGE);
            
            this.setVisible(false);
            FrmInsertSpecialization form = new FrmInsertSpecialization((Frame) this.getParent(), true, FormMode.FORM_VIEW_MODE, specialization);
            form.setVisible(true);
            
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Sistem ne može da zapamti specijalizaciju.", "Greška", JOptionPane.ERROR_MESSAGE);
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greška", JOptionPane.ERROR_MESSAGE);
        }
        
        
    }//GEN-LAST:event_btnSaveActionPerformed


