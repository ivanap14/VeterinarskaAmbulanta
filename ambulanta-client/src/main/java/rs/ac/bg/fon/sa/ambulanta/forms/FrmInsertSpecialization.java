    private void populateComboBox() {
        cbCategory.setModel(new DefaultComboBoxModel(Category.values()));
        cbCategory.setSelectedIndex(-1);
    }

    private void prepareView() {
        

        if(mode==FormMode.FORM_VIEW_MODE){
            
            txtName.setText(specialization.getName());
            cbCategory.setSelectedItem(specialization.getCategory());
            txtDescription.setText(specialization.getDescription());
            
            txtName.setEditable(false);
            txtDescription.setEditable(false);
            cbCategory.setEnabled(false);
            
            btnSave.setVisible(false);
            
        }
    }

